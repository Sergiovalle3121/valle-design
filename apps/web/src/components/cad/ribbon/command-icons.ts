/**
 * UN ICONO POR COMANDO. Catálogo propio, y por eso existe este archivo.
 *
 * ## Qué había, y qué se midió
 *
 * `ribbon-icons.ts` reparte un icono por PANEL: los veintiséis comandos de
 * «Modificar» salían los veintiséis con la misma llave inglesa. Era honesto
 * —no inventaba una distinción que la cinta no hacía— y era exactamente lo que
 * `docs/competitive/distancia-autocad-completo-20260903.md` cuenta entre los
 * tres reflejos caros que quedaban abiertos: **0 iconos por comando**. En
 * AutoCAD la cinta se lee por la FORMA del botón, no por su texto; una cinta de
 * iconos repetidos obliga a leer 247 rótulos.
 *
 * ## De dónde salen los dibujos
 *
 * De **lucide** (ISC, ya en el árbol de dependencias y ya declarado en
 * `THIRD_PARTY_NOTICES.md`). No hay ni un trazo de iconografía de Autodesk aquí
 * ni en ningún otro sitio del producto: eso no es una precaución, es la regla
 * de procedencia de la campaña. Lo que este archivo aporta es la ASIGNACIÓN
 * —qué dibujo le toca a cada orden—, que es trabajo propio y se lee como tal.
 *
 * ## Por qué la tabla es explícita y no un algoritmo
 *
 * Se probaron reglas por prefijo (`LAY*`, `DIM*`, `GC*`) y producen justo el
 * problema que venimos a quitar: trece restricciones geométricas idénticas. Lo
 * que un dibujante reconoce es que PARALELA no se parece a PERPENDICULAR, y eso
 * no lo deduce ningún prefijo. La tabla es larga a propósito.
 *
 * ## El contrato
 *
 * `command-icons.spec.ts` recorre el registro REAL y falla si un comando no
 * tiene icono. Un comando nuevo no puede entrar mudo en la cinta — la misma
 * regla que ya tienen los resúmenes de la paleta.
 */
