/**
 * El icono de un comando. Sin reposo a propósito: quien pregunte por uno que no
 * está recibe `null` y quien pinta decide qué hacer, en vez de dibujar un
 * genérico que oculta el hueco. El gate lo convierte en imposible.
 */
export function cadCommandIcon(command: string): LucideIcon | null {
  return CAD_COMMAND_ICONS[command.toUpperCase()] ?? null;
}
