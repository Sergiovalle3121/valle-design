/**
 * Rótulos cortos en español de los comandos del motor — el texto del BOTÓN de
 * la cinta.
 *
 * ## Por qué existe este archivo
 *
 * El botón de la cinta pintaba el nombre canónico en inglés (LINE, RECTANG,
 * MATCHPROP). En AutoCAD es-MX el botón dice «Línea», «Rectángulo», «Igualar
 * propiedades», y el nombre con su alias vive en el tooltip. El resumen
 * (`command-summaries.ts`) es una frase; aquí va lo que cabe en un botón:
 * una o dos palabras, tres como mucho.
 *
 * ## El contrato es FAIL-CLOSED, igual que el de los resúmenes
 *
 * Todo comando del registro tiene rótulo y ningún rótulo nombra un comando
 * que ya no existe (`command-labels.spec.ts`). `cadCommandLabel` lanza en
 * vez de devolver una cadena vacía: un botón mudo no es una opción.
 *
 * ## Qué dice cada rótulo
 *
 * Lo que el comando HACE en este producto, no lo que promete el nombre:
 * PLOT traza a PDF y por eso dice «Trazar a PDF»; los comandos con guion
 * («-LAYER») trabajan por la línea de comandos y lo dicen entre paréntesis.
 * Los botones pequeños de la cinta miden 6,75 rem (`CadRibbonButton.tsx`):
 * el rótulo de un comando que no es primario cabe en 16 caracteres, medido
 * a 11 px; los primarios se pintan grandes, con el rótulo en dos líneas, y
 * ahí lo que manda es que ninguna palabra pase de 12 caracteres.
 */

