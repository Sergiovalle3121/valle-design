// Los tres nombres de aplicación viajan en el archivo: registrados en la
// tabla APPID y usados como marca (código 1001) de cada entidad con
// metadatos semánticos.
for (const application of ["AXOS_DIM", "AXOS_MLEADER", "AXOS_BLOCK"]) {
  assert.ok(
    GOLDEN_DXF.includes(application),
    application + ' debe seguir presente en el golden',
  );
}

const imported = importDxfPrimitives(GOLDEN_DXF);
assert.deepEqual(imported.warnings, [], "el golden importa sin advertencias");

/* ── AXOS_DIM: cota semántica ───────────────────────────────────────────── */
assert.equal(imported.semanticDimensions.length, 1, "la cota semántica sobrevive");
const dimension = imported.semanticDimensions[0];
assert.equal(dimension.dimensionKind, "aligned");
assert.equal(dimension.layer, "DIMS");
assert.deepEqual(dimension.a, { x: 0, y: 0 });
assert.deepEqual(dimension.b, { x: 100, y: 0 });
assert.equal(dimension.offset, 25);
assert.equal(dimension.style, "Standard");
assert.equal(dimension.units, "mm");
assert.equal(dimension.arrowhead, "closed-filled");
assert.deepEqual(
  imported.primitiveSources,
  ["insert"],
  "el bloque *D de la cota no se duplica como geometría aplanada",
);

/* ── AXOS_MLEADER: directriz con texto ──────────────────────────────────── */
assert.equal(imported.mleaders.length, 1, "la directriz semántica sobrevive");
const mleader = imported.mleaders[0];
assert.equal(mleader.layer, "NOTES");
assert.equal(mleader.text, "Nota");
assert.deepEqual(mleader.textPosition, { x: 60, y: 55, z: 0 });
assert.equal(mleader.leaderLines?.length, 1);
assert.equal(mleader.contentType, "mtext");

/* ── AXOS_BLOCK: definición de bloque + atributos del INSERT ────────────── */
assert.equal(imported.blocks.length, 1, "la definición de bloque sobrevive");
const block = imported.blocks[0];
assert.equal(block.name, "PILAR");
assert.equal(block.version, 1);
assert.equal(block.attributes.TAG?.defaultValue, "P-1");
assert.equal(block.attributes.TAG?.prompt, "Tag");
assert.equal(imported.inserts.length, 1, "el INSERT vivo sobrevive");
assert.equal(imported.inserts[0].block, "PILAR");
assert.deepEqual(
  imported.inserts[0].attributes,
  { TAG: "P-7" },
  "los valores de atributo viajan en la XDATA AXOS_BLOCK del INSERT",
);

console.log("dxf-xdata-golden: AXOS_DIM / AXOS_MLEADER / AXOS_BLOCK legibles");
